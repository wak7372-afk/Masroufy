"""Train a small header classifier from scratch, locally, using standard Python only.

No downloaded weights, network calls, customer statements, or generative model.
The model classifies header text only; it never generates transaction values.
"""
import collections
import hashlib
import json
import math
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name('header_examples.json')
OUT = ROOT / 'shared/src/commonMain/kotlin/om/masroofi/core/LocalColumnWeights.kt'


def clean(text):
    text = unicodedata.normalize('NFKC', text).lower()
    for a, b in [('أ','ا'),('إ','ا'),('آ','ا'),('ى','ي'),('ة','ه')]:
        text = text.replace(a,b)
    return re.sub(r'\s+', ' ', re.sub(r'[\u064b-\u065f\u0670ـ]', '', text)).strip()


def features(text):
    text = '^' + re.sub(r'[^a-zء-ي ]', '', clean(text)) + '$'
    return set(text[i:i+n] for n in (2,3) for i in range(len(text)-n+1))


def train(labels):
    counts = {}
    for role, examples in labels.items():
        counts[role] = collections.Counter()
        for text in examples:
            counts[role].update(features(text))
    vocab = sorted(set().union(*(set(c) for c in counts.values())))
    weights = {role: [round(math.log((counts[role][f] + 0.25) / (sum(counts[role].values()) + len(vocab)*0.25)),5) for f in vocab] for role in labels}
    return {'v':1,'features':vocab,'weights':weights}


def write_model(data, output, symbol):
    labels = json.loads(data.read_text(encoding='utf-8'))
    trained = train(labels)
    model = json.dumps(trained, ensure_ascii=False, separators=(',',':'))
    source_hash = hashlib.sha256(data.read_bytes()).hexdigest()
    chunks = []
    remaining = model
    while len(remaining)>8000:
        boundary = remaining.rfind(',',0,8000)+1
        if not boundary: raise ValueError('Model token exceeds Kotlin chunk limit')
        chunks.append(remaining[:boundary]); remaining=remaining[boundary:]
    chunks.append(remaining)
    output.write_text('// Generated by tools/local_extractor/train.py. Training data SHA256: '+source_hash+'\npackage om.masroofi.core\n\ninternal val '+symbol+' = listOf(\n'+',\n'.join('\"\"\"'+chunk+'\"\"\"' for chunk in chunks)+'\n).joinToString(\"\")\n', encoding='utf-8', newline='\n')
    print(json.dumps({'model':symbol,'labels':len(labels),'examples':sum(map(len,labels.values())),'features':len(trained['features']),'model_bytes':len(model.encode()),'training_sha256':source_hash}))


def main():
    write_model(DATA, OUT, 'LOCAL_COLUMN_WEIGHTS')
    write_model(DATA.with_name('direction_examples.json'), OUT.with_name('LocalDirectionWeights.kt'), 'LOCAL_DIRECTION_WEIGHTS')


if __name__ == '__main__':
    main()
